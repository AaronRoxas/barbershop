import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { createClient, type WebSocketLikeConstructor } from "@supabase/supabase-js";
import { randomUUID } from "node:crypto";
import WebSocket from "ws";

test("owners manage the catalog and appointments; staff and guests respect access boundaries", async ({ page }, testInfo) => {
  test.setTimeout(90000);
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL!;
  expect(["127.0.0.1", "localhost"]).toContain(new URL(url).hostname);
  const admin = createClient(url, process.env.SUPABASE_SERVICE_ROLE_KEY!, { auth: { persistSession: false }, realtime: { transport: WebSocket as unknown as WebSocketLikeConstructor } });
  const verify = <T,>(r: { data: T; error: { message: string } | null }) => { expect(r.error?.message).toBeUndefined(); return r.data; };
  const business = verify(await admin.from("businesses").select("*").eq("slug", "reference").single())!;
  const suffix = randomUUID();
  const email = `admin-e2e-${suffix}@example.com`, password = `Admin!${randomUUID()}`, serviceName = `Browser cut ${suffix}`;
  const userResult = await admin.auth.admin.createUser({ email, password, email_confirm: true });
  expect(userResult.error).toBeNull();
  const user = userResult.data.user!;
  let serviceId: string | undefined;
  let uploaded: string | undefined;
  let fixtureBarber: string | undefined;
  const customerEmail = `admin-customer-${suffix}@example.com`;
  const accessible = async () => {
    await expect(page.locator(".loading-state")).toBeHidden();
    expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  };
  try {
    if (testInfo.project.name === "mobile") await page.setViewportSize({ width: 320, height: 900 });
    await page.goto("/admin/appointments");
    await expect(page).toHaveURL(/\/admin\/login/);
    await accessible();
    await page.getByLabel("Email", { exact: true }).fill(email);
    await page.getByLabel("Password").fill(password);
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(page.locator("main").getByRole("alert")).toContainText("no access");
    verify(await admin.from("business_members").insert({ business_id: business.id, user_id: user.id, role: "owner" }));
    await page.goto("/admin");
    await expect(page.getByRole("heading", { name: "Your day, at a glance." })).toBeVisible();
    const recovery = await admin.auth.admin.generateLink({ type: "recovery", email });
    expect(recovery.error).toBeNull();
    await page.goto(`/admin/auth/confirm?type=recovery&token_hash=${recovery.data.properties!.hashed_token}`);
    await expect(page).toHaveURL(/\/admin\/password$/);
    await page.getByLabel("New password", { exact: true }).fill(`${password}New`);
    await page.getByLabel("Confirm password", { exact: true }).fill(`${password}New`);
    await page.getByRole("button", { name: "Set password", exact: true }).click();
    await expect(page).toHaveURL(/\/admin$/);
    await accessible();
    await page.goto("/admin/services");
    await page.getByText("Add a service", { exact: true }).click();
    const create = page.locator("details").filter({ has: page.getByText("Add a service", { exact: true }) });
    await create.getByLabel("Service name").fill(serviceName);
    await create.getByLabel("Price (minor currency units)").fill("12345");
    await create.getByLabel("Duration (minutes)").fill("30");
    await create.getByLabel("Display order").fill("9999");
    await create.getByRole("button", { name: "Create service" }).click();
    await expect(page.getByRole("heading", { name: serviceName })).toBeVisible();
    const s = verify(await admin.from("services").select("*").eq("business_id", business.id).eq("name", serviceName).single())!;
    serviceId = s.id;
    const record = page.locator("article").filter({ has: page.getByRole("heading", { name: serviceName }) });
    await record.locator("summary").filter({ hasText: /^Upload image$/ }).click();
    await record.getByLabel(/Image \(JPEG/).setInputFiles({ name: "test.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aSq0AAAAASUVORK5CYII=", "base64") });
    await record.getByRole("button", { name: "Upload image" }).click();
    await expect(record.getByRole("status")).toContainText("Image uploaded");
    uploaded = verify(await admin.from("services").select("image_path").eq("id", serviceId).single())!.image_path;
    await accessible();
    const barber = verify(await admin.from("barbers").select("*").eq("business_id", business.id).eq("name", "Alex").single())!;
    verify(await admin.from("barber_services").insert({ business_id: business.id, service_id: serviceId, barber_id: barber.id }));
    const dateParts = new Intl.DateTimeFormat("en-CA", { timeZone: business.timezone, year: "numeric", month: "2-digit", day: "2-digit" }).formatToParts(new Date());
    const part = (name: string) => dateParts.find((p) => p.type === name)!.value;
    const day = `${part("year")}-${part("month")}-${part("day")}`;
    const allSlots = verify(await admin.rpc("booking_availability", { p_business: business.id, p_service: serviceId, p_barber: barber.id, p_date: day })) as { startsAt: string }[];
    const future = allSlots.filter((s) => s.startsAt.slice(0, 10) > day);
    expect(future.length).toBeGreaterThan(2);
    const local = (instant: string) => {
      const parts = new Intl.DateTimeFormat("en-CA", { timeZone: business.timezone, year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", second: "2-digit", hourCycle: "h23" }).formatToParts(new Date(instant));
      const p = (name: string) => parts.find((v) => v.type === name)!.value;
      return `${p("year")}-${p("month")}-${p("day")}T${p("hour")}:${p("minute")}`;
    };
    await page.goto("/admin/appointments/new");
    await page.getByRole("combobox", { name: "Service", exact: true }).selectOption(serviceId!);
    await page.getByRole("combobox", { name: "Barber", exact: true }).selectOption(barber.id);
    await page.getByLabel(/^Start \(/).fill(local(future[0].startsAt));
    await page.getByLabel("Customer name").fill("Admin Browser Customer");
    await page.getByLabel("Customer email").fill(customerEmail);
    await page.getByLabel("Customer phone").fill("+639123456789");
    await page.getByLabel("Customer notes").fill("Keep these details");
    await accessible();
    await page.getByRole("button", { name: "Create appointment" }).click();
    await expect(page).toHaveURL(/\/admin\/appointments\/[a-f0-9-]+\?saved=1/);
    await expect(page.getByRole("status")).toContainText("Appointment saved");
    await page.getByLabel(/^Start \(/).fill(local(future[2].startsAt));
    await page.getByRole("button", { name: "Save appointment" }).click();
    await expect.poll(async () => local(verify(await admin.from("appointments").select("starts_at").eq("customer_email", customerEmail).single())!.starts_at)).toBe(local(future[2].startsAt));
    const moved = verify(await admin.from("appointments").select("updated_at").eq("customer_email", customerEmail).single())!;
    await expect(page.locator('input[name="expected"]')).toHaveValue(moved.updated_at);
    await expect(page.getByLabel(/^Start \(/)).toHaveValue(local(future[2].startsAt));
    await expect(page.getByLabel("Customer notes")).toHaveValue("Keep these details");
    await page.getByRole("combobox", { name: "Status", exact: true }).selectOption("cancelled");
    await page.getByRole("button", { name: "Save appointment" }).click();
    await expect.poll(async () => verify(await admin.from("appointments").select("status").eq("customer_email", customerEmail).single())!.status).toBe("cancelled");
    await expect(page.getByRole("combobox", { name: "Status", exact: true })).toHaveValue("cancelled");
    await accessible();
    await page.screenshot({ path: testInfo.outputPath("admin-appointment.png"), fullPage: true });
    await page.goto("/admin/appointments?status=cancelled");
    await expect(page.locator(".admin-appointments")).toContainText("Admin Browser Customer");
    await accessible();
    await page.goto("/admin/barbers");
    await page.getByText("Add a barber", { exact: true }).click();
    const barberCreate = page.locator("details").filter({ has: page.getByText("Add a barber", { exact: true }) });
    const barberName = `Browser barber ${suffix}`;
    await barberCreate.getByLabel("Barber name").fill(barberName);
    await barberCreate.getByRole("button", { name: "Create barber" }).click();
    await expect(page.getByRole("heading", { name: barberName })).toBeVisible();
    fixtureBarber = verify(await admin.from("barbers").select("id").eq("business_id", business.id).eq("name", barberName).single())!.id;
    const barberRecord = page.locator("article").filter({ has: page.getByRole("heading", { name: barberName }) });
    await barberRecord.locator("summary").filter({ hasText: "Assign services" }).click();
    await barberRecord.getByLabel(serviceName, { exact: true }).check();
    await barberRecord.getByRole("button", { name: "Save changes" }).last().click();
    await expect(barberRecord.getByRole("status")).toContainText("Assigned services saved");
    await accessible();
    await page.goto("/admin/schedule");
    const weekly = page.locator("details").filter({ has: page.locator("summary").filter({ hasText: barberName }) });
    await weekly.locator("summary").click();
    await weekly.getByLabel("Monday", { exact: true }).fill("09:00-12:00, 13:00-19:00");
    await weekly.getByRole("button", { name: "Save weekly hours" }).click();
    await expect(weekly.getByRole("status")).toContainText("Weekly hours saved");
    const special = page.locator("article").filter({ has: page.getByRole("heading", { name: "Special dates" }) });
    await special.getByLabel("Applies to").selectOption(fixtureBarber!);
    await special.getByLabel("Date", { exact: true }).fill("2035-01-01");
    await special.getByRole("button", { name: "Add special date" }).click();
    await expect(special.locator(".admin-schedule-entry").filter({ hasText: barberName })).toContainText("Closed");
    await special.locator(".admin-schedule-entry").filter({ hasText: barberName }).getByRole("button", { name: "Remove" }).click();
    await expect(special.locator(".admin-schedule-entry").filter({ hasText: barberName })).toHaveCount(0);
    const off = page.locator("article").filter({ has: page.getByRole("heading", { name: "Time off & breaks" }) });
    await off.getByLabel("Applies to").selectOption(fixtureBarber!);
    await off.getByLabel("Start", { exact: true }).fill("2035-01-01T09:00");
    await off.getByLabel("End", { exact: true }).fill("2035-01-01T10:00");
    await off.getByLabel("Private reason (optional)").fill("Browser private reason");
    await off.getByRole("button", { name: "Block time" }).click();
    await expect(off.locator(".admin-schedule-entry").filter({ hasText: barberName })).toContainText("Browser private reason");
    await off.locator(".admin-schedule-entry").filter({ hasText: barberName }).getByRole("button", { name: "Remove" }).click();
    await expect(off.locator(".admin-schedule-entry").filter({ hasText: barberName })).toHaveCount(0);
    await accessible();
    await page.goto("/admin/settings"); await accessible();
    verify(await admin.from("business_members").update({ role: "staff" }).eq("business_id", business.id).eq("user_id", user.id));
    for (const route of ["services", "barbers", "schedule", "settings"]) {
      await page.goto(`/admin/${route}`);
      await expect(page).toHaveURL(/\/admin\?access=owner/);
    }
    await page.goto("/admin/appointments");
    await expect(page.getByRole("heading", { name: "Appointments", exact: true })).toBeVisible();
    verify(await admin.from("business_members").delete().eq("business_id", business.id).eq("user_id", user.id));
    await page.reload();
    await expect(page).toHaveURL(/\/admin\/login\?access=denied/);
    await page.getByRole("button", { name: "Sign out of this account" }).click();
    await expect(page).toHaveURL(/\/admin\/login$/);
  } finally {
    verify(await admin.from("appointments").delete().eq("business_id", business.id).eq("customer_email", customerEmail));
    if (serviceId) verify(await admin.from("services").delete().eq("business_id", business.id).eq("id", serviceId));
    if (fixtureBarber) verify(await admin.from("barbers").delete().eq("business_id", business.id).eq("id", fixtureBarber));
    if (uploaded) verify(await admin.storage.from("business-images").remove([uploaded]));
    expect((await admin.auth.admin.deleteUser(user.id)).error).toBeNull();
  }
});
